<#
.SYNOPSIS
    Refresh the mihomo rule-provider that carries the 911 provider's OWN proxy rules.

.DESCRIPTION
    The 911 subscription ships a full Clash config whose `rules:` section is its
    own opinion about what needs a proxy - 610 rules on 2026-10-11, of which 354
    names a domain and points it at its proxy group; the rest are DIRECT entries
    for its own infrastructure and the CN/private ranges, plus a MATCH tail that
    proxies everything.

    That tail is what this project does NOT want: with `MATCH,OpenConnectUs911`
    every foreign host spends quota. The owner's instruction (2026-10-11) is to
    keep the *rules* - they are the provider's curated must-proxy list - and let
    everything else go direct.

    So this script lifts the provider's domain rules (the ones whose target is its
    proxy group) into a classical rule-provider payload, which the live config then
    references with `RULE-SET,clashmi-911,<our chain>` and follows it with
    `MATCH,DISPATCH`.

    The file it writes is runtime state (runtime\rules\ is gitignored) and is
    regenerated whenever the subscription changes; the config only ever names it.

.PARAMETER ProviderPath
    The provider file mihomo downloads. Default: runtime\providers\clashmi.yaml.

.PARAMETER OutPath
    Where to write the payload. Default: runtime\rules\clashmi-911.yaml.

.PARAMETER ProxyGroup
    The provider's own proxy-group name; only rules targeting it are lifted.
    Default: OpenConnectUs911.

.EXAMPLE
    .\tools\Update-Clashmi911Rules.ps1
    .\tools\Update-Clashmi911Rules.ps1 -WhatIf
#>
[CmdletBinding()]
param(
    [string] $ProviderPath = 'C:\Users\victo\mihomo\runtime\providers\clashmi.yaml',
    [string] $OutPath      = 'C:\Users\victo\mihomo\runtime\rules\clashmi-911.yaml',
    [string] $ProxyGroup   = 'OpenConnectUs911',
    [switch] $WhatIf
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $ProviderPath)) {
    throw "provider not found: $ProviderPath (has mihomo fetched it yet?)"
}

# Read as UTF-8 explicitly: the provider carries CJK node names, and Windows
# PowerShell 5.1's Get-Content would decode them with the ANSI code page.
$text = [IO.File]::ReadAllText($ProviderPath, [Text.Encoding]::UTF8)

# The rules live in a top-level `rules:` block. The block ends at the next top-level KEY,
# not at the next column-0 line: (?=^\S) (the first version) also stopped at a column-0
# COMMENT, so a commented provider would silently truncate the rule list - the only
# backstop was the < 50 lifted rules warning. Measured 2026-10-11 against the config
# template, which has such a comment inside its own block.
$m = [regex]::Match($text, '(?ms)^rules:[ \t]*\r?\n(.*?)(?=^[A-Za-z][A-Za-z0-9_-]*:|\z)')
if (-not $m.Success) { throw "no top-level 'rules:' section in $ProviderPath" }

$all = @()
foreach ($line in ($m.Groups[1].Value -split "`r?`n")) {
    if ($line -notmatch "^\s*-\s*'?(.+?)'?\s*$") { continue }
    $all += $Matches[1].Trim().Trim("'")
}

# Rules whose target is the provider's own proxy group. `MATCH` is excluded: a
# provider payload cannot contain a catch-all, and the catch-all is precisely the
# thing this project replaces with MATCH,DISPATCH.
$proxy = @($all | Where-Object { $_ -match (',' + [regex]::Escape($ProxyGroup) + '\s*$') -and $_ -notmatch '^MATCH' })

# Sanity: a payload entry must be a rule WITHOUT a policy (classical behaviour).
$payload = foreach ($r in $proxy) {
    $parts  = $r -split ','
    $policy = $parts[-1].Trim()
    if ($policy -ne $ProxyGroup) { continue }
    (($parts[0..($parts.Count - 2)] -join ',')).Trim()
}

$byType = $payload | ForEach-Object { ($_ -split ',')[0] } | Group-Object | Sort-Object Count -Descending

Write-Host ''
Write-Host '  clashmi-911 rule provider' -ForegroundColor Cyan
Write-Host ("    provider      : {0}" -f $ProviderPath) -ForegroundColor DarkGray
Write-Host ("    rules in file : {0}" -f $all.Count)
Write-Host ("    -> proxy group: {0}  ({1} lifted)" -f $ProxyGroup, $payload.Count)
Write-Host ("    rule types    : {0}" -f (($byType | ForEach-Object { "$($_.Name)=$($_.Count)" }) -join ' ')) -ForegroundColor DarkGray

if ($payload.Count -lt 50) {
    Write-Host ("    WARNING: only {0} rules lifted - has the provider changed shape?" -f $payload.Count) -ForegroundColor Yellow
}

$stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')
$out = New-Object System.Collections.Generic.List[string]
$out.Add('# Auto-generated by tools/Update-Clashmi911Rules.ps1 - DO NOT EDIT BY HAND.')
$out.Add('# source   : ' + (Split-Path -Leaf $ProviderPath) + '  (the 911 subscription, fetched by mihomo)')
$out.Add('# meaning  : the provider''s own must-proxy domains, lifted out of its rules: block')
$out.Add('#            and used with RULE-SET,clashmi-911,<our chain> in runtime\config.yaml.')
$out.Add('#            Its DIRECT/CN/private entries and its MATCH tail are deliberately')
$out.Add('#            dropped: the config''s catch-all is MATCH,DISPATCH (owner, 2026-10-11),')
$out.Add('#            so anything not listed here goes direct.')
$out.Add('# generated: ' + $stamp)
$out.Add('# entries  : ' + $payload.Count)
$out.Add('payload:')
foreach ($p in $payload) { $out.Add("  - '" + $p + "'") }

if ($WhatIf) {
    Write-Host '    -WhatIf: nothing written' -ForegroundColor Yellow
    return
}

$dir = Split-Path -Parent $OutPath
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
$tmp = "$OutPath.tmp"
[IO.File]::WriteAllText($tmp, (($out -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding($false)))
Move-Item -LiteralPath $tmp -Destination $OutPath -Force
Write-Host ("    written       : {0}" -f $OutPath) -ForegroundColor Green
Write-Host ''
